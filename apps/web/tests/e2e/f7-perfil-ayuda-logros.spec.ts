import { expect, test } from "@playwright/test"
import { login, shot, watchErrors } from "./helpers"

test("perfil, novedades, preguntas, manual, tour y logros", async ({ page }, info) => {
  test.setTimeout(240_000)
  const errs = watchErrors(page)
  await login(page)

  await page.goto("/perfil")
  await expect(page.getByText("¿Quiénes hacen parte de tu hogar?")).toBeVisible({ timeout: 30_000 })
  // Avatar al estilo Netflix: avatares de Mirai por categorías (abre en Financiero) + iniciales
  await page.getByRole("button", { name: "Cambiar avatar" }).first().click()
  const picker = page.getByRole("dialog", { name: "Elige tu avatar" })
  await expect(picker.getByRole("radio", { name: "Cohete" })).toBeVisible()
  await expect(picker.getByRole("radio", { name: "Solo iniciales" })).toBeVisible()
  await picker.getByRole("radio", { name: "Cohete" }).click()
  await expect(page.getByText("Avatar actualizado")).toBeVisible()
  await expect(page.getByRole("img", { name: "Avatar Cohete" }).first()).toBeVisible()
  await expect(page.getByText(/Tu perfil está al \d+ %/)).toBeVisible()
  // Portada: escenas por categoría, colores y la foto propia (aquí se escoge una escena).
  // Se espera a que la ventana del avatar termine de cerrarse (dos ventanas cruzadas bloquean los clics).
  await expect(picker).toBeHidden()
  await page.getByRole("button", { name: "Cambiar portada" }).click()
  const portada = page.getByRole("dialog", { name: "Ponle una portada a tu perfil" })
  await expect(portada).toBeVisible()
  await portada.getByRole("tab", { name: /Naturaleza/ }).click()
  await portada.getByRole("radio", { name: "Playa" }).click()
  await expect(page.getByText("Portada actualizada")).toBeVisible()
  // Teléfono: se acomoda solo mientras se escribe
  const tel = page.getByRole("textbox", { name: "Teléfono" })
  await tel.fill("3001234567")
  await expect(tel).toHaveValue("300 123 4567")
  await tel.blur()
  // Meta financiera: tipo, monto, fecha, avance y pasos
  await page.getByRole("button", { name: "Escoger mi meta" }).click()
  const metaDlg = page.getByRole("dialog", { name: "¿Cuál es tu meta?" })
  await metaDlg.getByRole("radio", { name: /Comprar vivienda/ }).click()
  await metaDlg.getByRole("textbox", { name: "¿Cómo la llamas?" }).fill("Cuota inicial del apartamento")
  await metaDlg.getByRole("textbox", { name: "¿Cuánto necesitas?" }).fill("60000000")
  await metaDlg.getByRole("button", { name: "Guardar mi meta" }).click()
  await expect(page.getByText("Tu meta quedó lista")).toBeVisible()
  const metaCard = page.locator("#meta")
  await expect(metaCard.getByText("Cuota inicial del apartamento")).toBeVisible()
  await expect(metaCard.getByText(/Te faltan/)).toBeVisible()
  // Un paso que se marca a mano queda guardado
  await metaCard.getByRole("checkbox", { name: /cuota inicial/i }).first().check()
  await expect(metaCard.getByRole("checkbox", { name: /cuota inicial/i }).first()).toBeChecked()
  // Cédula → los 2 dígitos de la DIAN salen solos
  const doc = page.getByRole("textbox", { name: "Número de documento" })
  await doc.fill("1.020.345.678")
  await doc.blur()
  await expect(page.getByText("termina en 78")).toBeVisible()
  // Recibe pagos: agregar Nequi, ver el texto para compartir y quitarlo (el flujo completo está en f16-recibe-pagos)
  const cobro = page.locator("#cobro")
  await cobro.getByRole("button", { name: "Agregar", exact: true }).first().click()
  const dlg = page.getByRole("dialog", { name: "Agregar un medio de pago" })
  await dlg.getByRole("button", { name: "Elegir Nequi" }).click()
  await dlg.getByRole("textbox", { name: "Celular" }).fill("3001234567")
  await dlg.getByRole("button", { name: "Agregar", exact: true }).click()
  await expect(cobro.getByText("300 123 4567")).toBeVisible()
  await cobro.getByRole("button", { name: "Código QR", exact: true }).click()
  await expect(page.getByRole("dialog", { name: "Tu código para recibir pagos" }).getByText("• Nequi: 300 123 4567")).toBeVisible()
  await page.keyboard.press("Escape")
  await cobro.getByRole("button", { name: "Más opciones de Número Nequi de Nequi" }).click()
  await page.getByRole("menuitem", { name: "Eliminar" }).click()
  await expect(cobro.getByText("300 123 4567")).toHaveCount(0)
  await page.getByRole("textbox", { name: "Ocupación" }).fill(`Ingeniera QA ${Date.now() % 10000}`)
  await page.getByRole("textbox", { name: "Ocupación" }).blur()
  await expect(page.getByText("Guardado").first()).toBeVisible()
  // Integrantes: la misma lista de Ajustes › Hogar (Agregar persona › Solo agregarla al hogar)
  await page.locator("#famCard").getByRole("button", { name: "Agregar persona" }).click()
  await page.getByRole("radio", { name: "Solo agregarla al hogar" }).click()
  await page.getByRole("button", { name: "Continuar" }).click()
  const name = `Sofía ${Date.now() % 1000}`
  await page.getByRole("textbox", { name: "Nombre" }).fill(name)
  await page.getByRole("button", { name: "Agregar", exact: true }).click()
  await expect(page.getByText(`${name} ya hace parte de tu hogar.`)).toBeVisible()
  await page.getByRole("button", { name: `Opciones de ${name}` }).click()
  await page.getByRole("menuitem", { name: "Quitar del hogar" }).click()
  await page.getByRole("button", { name: "Quitar", exact: true }).click()
  await expect(page.getByText(`${name} ya no está en el hogar`)).toBeVisible()
  await shot(page, "perfil", info.project.name)

  await page.goto("/novedades")
  await expect(page.getByText("Mirai en la nube: tu familia, en tiempo real").first()).toBeVisible()
  await page.goto("/faq")
  await page.getByRole("textbox", { name: "Buscar en preguntas frecuentes" }).fill("contador")
  await expect(page.getByRole("button", { name: "¿Cómo le doy acceso a mi contador?" })).toBeVisible()
  await expect(page.getByText(/quitarle el acceso cuando quieras/)).toBeVisible()
  await page.goto("/manual")
  await page.getByRole("button", { name: /Registrar tu primer gasto/ }).click()
  await expect(page.getByText(/la categoría se elige sola/)).toBeVisible()
  await page.getByRole("radio", { name: /Manual por sección/ }).click()
  await expect(page.getByRole("heading", { name: "Gastos" }).first()).toBeVisible()

  await page.goto("/inicio?tour=1")
  await expect(page.getByRole("dialog", { name: "Tour de Mirai" })).toBeVisible({ timeout: 15_000 })
  await shot(page, "tour", info.project.name)
  await page.getByRole("button", { name: "Siguiente" }).click()
  await page.getByRole("button", { name: "Saltar" }).click()
  await expect(page.getByRole("dialog", { name: "Tour de Mirai" })).toHaveCount(0)

  await page.goto("/logros")
  await expect(page.getByText("Misiones de la semana")).toBeVisible({ timeout: 30_000 })
  await expect(page.getByText("Me presento")).toBeVisible()
  await expect(page.getByText(/Nivel \d/).first()).toBeVisible()
  await shot(page, "logros", info.project.name)
  await page.goto("/inicio")
  await expect(page.getByRole("link", { name: /Nivel \d · / })).toBeVisible({ timeout: 30_000 })
  expect(errs, errs.join("\n")).toEqual([])
})
