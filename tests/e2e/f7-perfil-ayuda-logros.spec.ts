import { expect, test } from "@playwright/test"
import { login, shot, watchErrors } from "./helpers"

test("perfil, novedades, preguntas, manual, tour y logros", async ({ page }, info) => {
  test.setTimeout(240_000)
  const errs = watchErrors(page)
  await login(page)

  await page.goto("/perfil")
  await expect(page.getByText("¿Quiénes hacen parte de tu hogar?")).toBeVisible({ timeout: 30_000 })
  // Avatar al estilo Netflix: 10 avatares de Mirai + iniciales
  await page.getByRole("button", { name: "Cambiar avatar" }).first().click()
  const picker = page.getByRole("dialog", { name: "Elige tu avatar" })
  await expect(picker.getByRole("radio")).toHaveCount(await picker.getByRole("radio", { name: "Foto de Google" }).count() + 12)
  await picker.getByRole("radio", { name: "Cohete" }).click()
  await expect(page.getByText("Avatar actualizado")).toBeVisible()
  await expect(page.getByRole("img", { name: "Avatar Cohete" }).first()).toBeVisible()
  await expect(page.getByText(/Tu perfil está al \d+ %/)).toBeVisible()
  // Cédula → los 2 dígitos de la DIAN salen solos
  const doc = page.getByRole("textbox", { name: "Número de documento" })
  await doc.fill("1.020.345.678")
  await doc.blur()
  await expect(page.getByText("termina en 78")).toBeVisible()
  // Recibe pagos: agregar Nequi, ver el texto para compartir y quitarlo
  await page.locator("#cobro").getByRole("button", { name: "Agregar" }).click()
  const dlg = page.getByRole("dialog", { name: "Agregar un medio de pago" })
  await dlg.getByRole("radio", { name: "Nequi" }).click()
  await dlg.getByRole("textbox", { name: "Celular" }).fill("3001234567")
  await dlg.getByRole("button", { name: "Agregar", exact: true }).click()
  await expect(page.locator("#cobro").getByText("300 123 4567")).toBeVisible()
  await page.locator("#cobro").getByRole("button", { name: "Código QR" }).click()
  await expect(page.getByRole("dialog", { name: "Tu código para recibir pagos" }).getByText("• Nequi: 300 123 4567")).toBeVisible()
  await page.keyboard.press("Escape")
  await page.locator("#cobro").getByRole("button", { name: "Quitar Nequi" }).click()
  await expect(page.locator("#cobro").getByText("300 123 4567")).toHaveCount(0)
  await page.getByRole("textbox", { name: "Ocupación" }).fill(`Ingeniera QA ${Date.now() % 10000}`)
  await page.getByRole("textbox", { name: "Ocupación" }).blur()
  await expect(page.getByText("Guardado").first()).toBeVisible()
  await page.getByRole("button", { name: "Agregar integrante" }).click()
  const name = `Sofía ${Date.now() % 1000}`
  await page.getByRole("textbox", { name: "Nombre" }).fill(name)
  await page.getByRole("button", { name: "Agregar", exact: true }).click()
  await expect(page.getByText(`${name} ya hace parte de tu familia en Mirai.`)).toBeVisible()
  await page.getByRole("button", { name: `Eliminar ${name}` }).click()
  await expect(page.getByText("Integrante eliminado")).toBeVisible()
  await shot(page, "perfil", info.project.name)

  await page.goto("/novedades")
  await expect(page.getByText("Mirai en la nube: tu familia, en tiempo real").first()).toBeVisible()
  await page.goto("/faq")
  await page.getByRole("textbox", { name: "Buscar en preguntas frecuentes" }).fill("contador")
  await expect(page.getByRole("button", { name: "¿Cómo le doy acceso a mi contador?" })).toBeVisible()
  await expect(page.getByText(/quitarle el acceso cuando quieras/)).toBeVisible()
  await page.goto("/manual")
  await page.getByRole("button", { name: /Registrar tu primer gasto/ }).click()
  await expect(page.getByText(/la categoría se elige sola/)).toBeVisible()
  await page.getByRole("radio", { name: /Manual por sección/ }).click()
  await expect(page.getByRole("heading", { name: "Gastos" }).first()).toBeVisible()

  await page.goto("/inicio?tour=1")
  await expect(page.getByRole("dialog", { name: "Tour de Mirai" })).toBeVisible({ timeout: 15_000 })
  await shot(page, "tour", info.project.name)
  await page.getByRole("button", { name: "Siguiente" }).click()
  await page.getByRole("button", { name: "Saltar" }).click()
  await expect(page.getByRole("dialog", { name: "Tour de Mirai" })).toHaveCount(0)

  await page.goto("/logros")
  await expect(page.getByText("Misiones de la semana")).toBeVisible({ timeout: 30_000 })
  await expect(page.getByText("Me presento")).toBeVisible()
  await expect(page.getByText(/Nivel \d/).first()).toBeVisible()
  await shot(page, "logros", info.project.name)
  await page.goto("/inicio")
  await expect(page.getByRole("link", { name: /Nivel \d · / })).toBeVisible({ timeout: 30_000 })
  expect(errs, errs.join("\n")).toEqual([])
})
