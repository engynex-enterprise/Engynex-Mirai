import { expect, test } from "@playwright/test"
import { login, shot, watchErrors } from "./helpers"

test("metas, fondo de emergencia, inversiones y salir de deudas con datos de ejemplo", async ({ page }, info) => {
  test.setTimeout(180_000)
  const errs = watchErrors(page)
  await login(page)
  await page.goto("/metas")
  await expect(page.getByText("Fondo de emergencia").first()).toBeVisible()
  await page.getByRole("button", { name: "Guardar dinero" }).click()
  await page.getByRole("textbox", { name: "¿Cuánto guardas?" }).fill("300000")
  await page.getByRole("dialog").getByRole("button", { name: "Guardar" }).click()
  await expect(page.getByText(/Guardaste .* Tu fondo tiene/)).toBeVisible()
  await page.getByRole("button", { name: "Usar para un imprevisto" }).click()
  await page.getByRole("textbox", { name: "¿Qué pasó?" }).fill("Se dañó la nevera")
  await page.getByRole("textbox", { name: "¿Cuánto costó?" }).fill("120000")
  await page.getByRole("button", { name: "Registrar imprevisto" }).click()
  await expect(page.getByText(/Pagado con el fondo/)).toBeVisible()
  await page.getByRole("button", { name: "Nueva meta" }).click()
  await page.getByRole("textbox", { name: "¿Qué quieres lograr?" }).fill(`Viaje ${info.project.name}`)
  await page.getByRole("textbox", { name: "¿Cuánto necesitas?" }).fill("8000000")
  await page.getByRole("button", { name: "Guardar meta" }).click()
  await expect(page.getByText("Meta creada")).toBeVisible()
  await expect(page.getByText(`Viaje ${info.project.name}`)).toBeVisible()
  await shot(page, "metas", info.project.name)
  await page.goto("/inversiones?nuevo=1")
  await page.getByRole("textbox", { name: "Nombre" }).fill("CDT prueba")
  await page.getByRole("textbox", { name: "¿Cuánto invertiste?" }).fill("15000000")
  await page.getByRole("textbox", { name: "Tasa E.A. (%)" }).fill("9,8")
  await page.getByRole("button", { name: "Guardar" }).click()
  await expect(page.getByText(/Al final recibirás/).first()).toBeVisible()
  await shot(page, "inversiones", info.project.name)
  await page.goto("/estrategia")
  await expect(page.getByText(/Registra tus créditos en Le debo|Avalancha/).first()).toBeVisible()
  expect(errs, errs.join("\n")).toEqual([])
})
